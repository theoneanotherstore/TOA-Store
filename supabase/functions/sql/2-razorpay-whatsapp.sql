-- Razorpay payments + WhatsApp (OTP sign-up, order confirmation, follow-ups, offers).
-- Run once in Supabase SQL Editor (safe to re-run). Run customer-accounts.sql first.

-- ---------- Razorpay: pending payments (the admin already reads this table for refunds) ----------
create table if not exists public.razorpay_pending (rzp_order_id text primary key);
alter table public.razorpay_pending
  add column if not exists status text not null default 'created',      -- created, processing, done, error, refunded
  add column if not exists amount integer not null default 0,           -- paise
  add column if not exists customer jsonb not null default '{}',
  add column if not exists items jsonb not null default '[]',
  add column if not exists payment_id text,
  add column if not exists order_number text,
  add column if not exists error text,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();
alter table public.razorpay_pending enable row level security;
-- old policies let ANY logged-in user (including customers) read every pending payment: remove them
drop policy if exists "Team reads razorpay_pending" on public.razorpay_pending;
drop policy if exists "Team updates razorpay_pending" on public.razorpay_pending;
drop policy if exists "Staff read razorpay_pending" on public.razorpay_pending;
create policy "Staff read razorpay_pending" on public.razorpay_pending for select to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid()));
drop policy if exists "Staff update razorpay_pending" on public.razorpay_pending;
create policy "Staff update razorpay_pending" on public.razorpay_pending for update to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid()))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid()));
grant select, update on public.razorpay_pending to authenticated;

alter table public.orders add column if not exists razorpay_payment_id text;
alter table public.orders add column if not exists razorpay_order_id text;
create unique index if not exists orders_razorpay_payment_uq on public.orders(razorpay_payment_id) where razorpay_payment_id is not null;
alter table public.orders add column if not exists wa_confirm_sent_at timestamptz;

-- ---------- WhatsApp: codes and message log ----------
create table if not exists public.wa_otps (
  id bigint generated by default as identity primary key,
  phone text not null, purpose text not null check (purpose in ('signup','login')),
  code_hash text not null, name text, email text, marketing boolean not null default false,
  attempts int not null default 0, expires_at timestamptz not null,
  consumed_at timestamptz, created_at timestamptz not null default now()
);
create index if not exists wa_otps_phone_idx on public.wa_otps (phone, created_at desc);
alter table public.wa_otps enable row level security;        -- no policies: only the server can touch it

create table if not exists public.wa_messages (
  id bigint generated by default as identity primary key,
  direction text not null default 'out', phone text, template text,
  status text, wa_message_id text, error text, text text, ref text,
  created_at timestamptz not null default now()
);
create index if not exists wa_messages_msg_idx on public.wa_messages (wa_message_id);
alter table public.wa_messages enable row level security;
drop policy if exists "Staff read wa_messages" on public.wa_messages;
create policy "Staff read wa_messages" on public.wa_messages for select to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid()));
grant select on public.wa_messages to authenticated;

-- ---------- customer accounts: offers consent, and the phone can no longer be edited by the customer ----------
do $$
begin
  if to_regclass('public.customer_accounts') is null then
    raise notice 'customer_accounts is missing: run customer-accounts.sql first, then re-run this file.';
    return;
  end if;
  alter table public.customer_accounts add column if not exists marketing_opt_in boolean not null default false;
  alter table public.customer_accounts add column if not exists marketing_opt_in_at timestamptz;
  alter table public.customer_accounts add column if not exists wa_opted_out_at timestamptz;
  revoke update on public.customer_accounts from authenticated;
  grant update (name) on public.customer_accounts to authenticated;     -- phone is verified by WhatsApp code, so it is not editable
  drop index if exists public.customer_accounts_phone_idx;
  begin
    create unique index if not exists customer_accounts_phone_uq on public.customer_accounts (right(regexp_replace(coalesce(phone,''), '\D', '', 'g'), 10)) where phone is not null;
  exception when others then
    raise notice 'Could not make phone numbers unique (duplicates exist). Fix the duplicate accounts, then re-run.';
  end;
end $$;

-- ---------- helpers used by the Edge Functions (server only) ----------
create or replace function public.wa_find_account(p text) returns table (id uuid, name text, email text, marketing_opt_in boolean)
language sql stable security definer set search_path = public as $$
  select a.id, a.name, a.email, a.marketing_opt_in from public.customer_accounts a
  where right(regexp_replace(coalesce(a.phone,''), '\D', '', 'g'), 10) = p limit 1
$$;
create or replace function public.wa_email_taken(e text) returns boolean
language sql stable security definer set search_path = public, auth as $$
  select exists (select 1 from auth.users u where lower(u.email) = lower(e))
$$;
create or replace function public.wa_set_marketing(p text, v boolean) returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  update public.customer_accounts set
    marketing_opt_in = v,
    marketing_opt_in_at = case when v then now() else marketing_opt_in_at end,
    wa_opted_out_at = case when v then null else now() end
  where right(regexp_replace(coalesce(phone,''), '\D', '', 'g'), 10) = right(regexp_replace(p, '\D', '', 'g'), 10);
  get diagnostics n = row_count; return n;
end $$;
create or replace function public.wa_is_opted_out(p text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.customer_accounts a where a.wa_opted_out_at is not null
                   and right(regexp_replace(coalesce(a.phone,''), '\D', '', 'g'), 10) = p)
      or (to_regclass('public.rec_optouts') is not null and exists (select 1 from public.rec_optouts o
                   where o.channel = 'whatsapp' and right(regexp_replace(coalesce(o.phone,''), '\D', '', 'g'), 10) = p))
$$;
create or replace function public.wa_offer_audience() returns table (name text, phone text)
language sql stable security definer set search_path = public as $$
  select a.name, right(regexp_replace(a.phone, '\D', '', 'g'), 10) from public.customer_accounts a
  where a.marketing_opt_in and a.wa_opted_out_at is null and coalesce(a.phone,'') <> ''
$$;
-- a logged-in customer can switch offers on or off for their own account
create or replace function public.set_my_marketing(v boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'Please log in'; end if;
  update public.customer_accounts set marketing_opt_in = v,
    marketing_opt_in_at = case when v then now() else marketing_opt_in_at end,
    wa_opted_out_at = case when v then null else now() end
  where id = auth.uid();
end $$;

revoke all on function public.wa_find_account(text), public.wa_email_taken(text), public.wa_set_marketing(text, boolean),
  public.wa_is_opted_out(text), public.wa_offer_audience(), public.set_my_marketing(boolean) from public, anon, authenticated;
grant execute on function public.wa_find_account(text), public.wa_email_taken(text), public.wa_set_marketing(text, boolean),
  public.wa_is_opted_out(text), public.wa_offer_audience() to service_role;
grant execute on function public.set_my_marketing(boolean) to authenticated;
